"""The line that marks a file as written by team-adapt (spec section 5.2)."""

SIGNATURE = "Generated by agent-team team-adapt"
TEXT = SIGNATURE + " from %s. Do not edit; edit the source and rerun team-adapt."
HEAD_LINES = 3


def hash_line(source):
    return "# " + TEXT % source


def html_line(source):
    return "<!-- " + TEXT % source + " -->"


def after_first_line(text, line):
    """Answer text with line inserted after its first line (inside YAML front matter)."""
    first, rest = text.split("\n", 1)
    return first + "\n" + line + "\n" + rest


def is_generated(text):
    return SIGNATURE in "\n".join(text.split("\n")[:HEAD_LINES])
